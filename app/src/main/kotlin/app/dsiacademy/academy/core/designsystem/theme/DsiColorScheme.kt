package app.dsiacademy.academy.core.designsystem.theme

import androidx.compose.runtime.Immutable
import androidx.compose.ui.graphics.Color

@Immutable
data class DsiColorScheme(
    val bgApp: Color,
    val bgSurface: Color,
    val bgSurfaceAlt: Color,
    val bgDarkPremium: Color,
    val bgDarkCard: Color,
    val textPrimary: Color,
    val textSecondary: Color,
    val textMuted: Color,
    val textOnDark: Color,
    val goldPrestige: Color,
    val goldLight: Color,
    val goldBorder: Color,
    val bluePrimary: Color,
    val blueLight: Color,
    val borderLight: Color,
    val glassBg: Color,
    val glassBorder: Color,
    val error: Color,
    val errorSoft: Color,
    val success: Color,
    val successSoft: Color,
    val warning: Color,
    val info: Color,
    val isDark: Boolean,
)

fun lightDsiColorScheme() = DsiColorScheme(
    bgApp = DsiColors.BgApp,
    bgSurface = DsiColors.BgSurface,
    bgSurfaceAlt = DsiColors.BgSurfaceAlt,
    bgDarkPremium = DsiColors.BgDarkPremium,
    bgDarkCard = DsiColors.BgDarkCard,
    textPrimary = DsiColors.TextPrimary,
    textSecondary = DsiColors.TextSecondary,
    textMuted = DsiColors.TextMuted,
    textOnDark = DsiColors.TextOnDark,
    goldPrestige = DsiColors.GoldPrestige,
    goldLight = DsiColors.GoldLight,
    goldBorder = DsiColors.GoldBorder,
    bluePrimary = DsiColors.BluePrimary,
    blueLight = DsiColors.BlueLight,
    borderLight = DsiColors.BorderLight,
    glassBg = DsiColors.GlassBgLight,
    glassBorder = DsiColors.GlassBorderLight,
    error = DsiColors.Error,
    errorSoft = DsiColors.ErrorSoft,
    success = DsiColors.Success,
    successSoft = DsiColors.SuccessSoft,
    warning = DsiColors.Warning,
    info = DsiColors.Info,
    isDark = false,
)

